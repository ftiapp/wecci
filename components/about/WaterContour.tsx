/**
 * ฉากหลังเส้นสายน้ำ — เส้นโค้งขนานกันแบบเส้นชั้นความลึกในแผนที่น้ำ
 *
 * ใช้แทนลายเมฆกับกังหันของหน้าโครงสร้างบุคลากร เพื่อให้สองหน้าไม่ซ้ำภาษาเดียวกัน
 * แต่ยังพูดเรื่องน้ำเหมือนกัน สอดคล้องกับงานหลักของสถาบันฯ
 *
 * ทุกเส้นจางมาก ตั้งใจให้เห็นเป็นเนื้อพื้นหลัง ไม่ใช่ภาพประกอบที่ต้องมอง
 * preserveAspectRatio="none" ให้ทรงยืดตามความสูงของเซกชัน ไม่ว่ารายชื่อจะยาวแค่ไหน
 */
export function WaterContour({ className = "" }: { className?: string }) {
  /*
    เส้นชุดเดียวเลื่อนลงทีละขั้น ได้ผลเป็นริ้วขนานที่ค่อย ๆ คลี่ออก
    เขียนเป็นลูปดีกว่าไล่พิมพ์ทีละเส้น เวลาปรับจำนวนหรือระยะห่างจะได้แก้ที่เดียว
  */
  const lines = Array.from({ length: 9 }, (_, i) => i);

  return (
    <svg
      className={`h-full w-full ${className}`}
      viewBox="0 0 1440 900"
      preserveAspectRatio="none"
      fill="none"
      aria-hidden
    >
      {lines.map((i) => (
        <path
          key={i}
          d={`M-40 ${120 + i * 88} C 300 ${40 + i * 88}, 620 ${240 + i * 88}, 960 ${
            150 + i * 88
          } S 1340 ${20 + i * 88}, 1480 ${110 + i * 88}`}
          stroke="var(--wecci-aqua)"
          strokeWidth={4}
          /* เส้นบนสุดเข้มสุดแล้วไล่จางลง สายตาจึงไม่ถูกดึงไปกองอยู่กลางหน้า */
          strokeOpacity={0.22 - i * 0.016}
          strokeLinecap="round"
        />
      ))}
    </svg>
  );
}
